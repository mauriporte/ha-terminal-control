<#
.SYNOPSIS
  Terminal Control: a Windows terminal (running Claude Code or any command) in a Home Assistant dashboard, via ttyd.

.DESCRIPTION
  Installs ttyd with winget, writes a launcher that starts it hidden at logon, and (with -TunnelHost, as admin)
  adds a Windows Firewall rule so only your tunnel/reverse-proxy machine can reach the port.

  ttyd is started with --auth-header: it only serves requests that carry the identity header your access proxy adds
  (Cloudflare Access by default). Never expose the port without that proxy in front: see the README.

.EXAMPLE
  .\install.ps1                                   # ttyd + launcher (current user), command "claude"
  .\install.ps1 -Command "pwsh -NoLogo"           # any other command
  .\install.ps1 -TunnelHost <tunnel-host-ip> -FirewallOnly   # as administrator: firewall rule only
#>
[CmdletBinding()]
param(
    [int]$Port = 7681,
    [string]$Command = "claude",
    [string]$WorkingDirectory = $env:USERPROFILE,
    [string]$AuthHeader = "Cf-Access-Authenticated-User-Email",
    [string]$TunnelHost,
    [switch]$FirewallOnly,
    [switch]$Startup
)
$ErrorActionPreference = "Stop"
$dir = Join-Path $env:LOCALAPPDATA "terminal-control"

function New-LauncherText {
    <# The VBScript launcher: hidden window, ttyd with the auth header, the command in PowerShell. #>
    param([int]$Port, [string]$Command, [string]$WorkingDirectory, [string]$AuthHeader)
    if ($AuthHeader -notmatch '^[A-Za-z0-9-]+$') { throw "AuthHeader must be a plain header name" }
    $cmd = $Command.Replace('"', '""""')
    $wd = $WorkingDirectory.Replace("'", "''")
    @"
' Terminal Control launcher (generated by install.ps1). Starts ttyd hidden; it serves a PowerShell running the command.
' CLAUDE* variables are cleared first: a Claude Code session that started this launcher would otherwise pass its
' CLAUDE_CODE_CHILD_SESSION marker down, and the terminal's Claude would not save its transcripts.
Set sh = CreateObject("WScript.Shell")
ttyd = sh.ExpandEnvironmentStrings("%LOCALAPPDATA%") & "\Microsoft\WinGet\Links\ttyd.exe"
cmd = """" & ttyd & """ -p $Port -W -H $AuthHeader -m 3 " & _
      "-t titleFixed=Terminal -t fontSize=15 -t ""theme={'background':'#000000'}"" -t disableLeaveAlert=true " & _
      "powershell.exe -NoLogo -NoExit -Command ""Get-ChildItem Env:CLAUDE* | Remove-Item; Set-Location '$wd'; $cmd"""
sh.Run cmd, 0, False
"@
}

if (-not $FirewallOnly) {
    if (-not (Get-Command ttyd -ErrorAction SilentlyContinue) -and
        -not (Test-Path "$env:LOCALAPPDATA\Microsoft\WinGet\Links\ttyd.exe")) {
        winget install --id tsl0922.ttyd --exact --silent --accept-package-agreements --accept-source-agreements
    }
    New-Item -ItemType Directory -Force $dir | Out-Null
    $launcher = Join-Path $dir "terminal-control.vbs"
    New-LauncherText -Port $Port -Command $Command -WorkingDirectory $WorkingDirectory -AuthHeader $AuthHeader |
        Set-Content -Encoding ASCII $launcher
    Write-Host "Launcher: $launcher"
    if ($Startup) {
        Copy-Item $launcher (Join-Path ([Environment]::GetFolderPath("Startup")) "terminal-control.vbs") -Force
        Write-Host "Added to the Startup folder (starts at logon)."
    } else {
        Write-Host "Start it now:  wscript `"$launcher`"   (add -Startup to start it at every logon)"
    }
}

if ($TunnelHost) {
    $admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
        [Security.Principal.WindowsBuiltInRole]::Administrator)
    if (-not $admin) { throw "The firewall rule needs an elevated PowerShell (run as administrator)." }
    # Windows blocks inbound by default: one allow rule scoped to the tunnel host. (A block rule would win over it.)
    Get-NetFirewallRule -DisplayName "Terminal Control*" -ErrorAction SilentlyContinue | Remove-NetFirewallRule
    New-NetFirewallRule -DisplayName "Terminal Control (ttyd) - tunnel host only" -Direction Inbound -Protocol TCP `
        -LocalPort $Port -RemoteAddress $TunnelHost -Action Allow -Profile Any | Out-Null
    Write-Host "Firewall: port $Port open only to $TunnelHost."
}
